test("menu và URL không suy quyền từ ADMIN, phòng hoặc vai trò ở quan hệ khác", () => {
  const user = { MaChucVu: "ADMIN", DonVi: [{ MaChucVu: "TP", MaDonVi: "P_KH" }, { MaChucVu: "VC", MaDonVi: "P_TCHC" }] };
  const access = (path, q) => canAccessPath(path, user, { LaQuanLy: true }, { LaQuanLy: true }, { LaQuanLy: true }, q);
  expect(access("/khen-thuong-dot-xuat")).toBe(false);
  expect(access("/khen-thuong-dot-xuat/uy-quyen", { Success: true, DuocNhap: true, DuocUyQuyen: true, LaQuanLy: false })).toBe(false);
  expect(access("/khen-thuong-dot-xuat/uy-quyen", { LaQuanLy: true })).toBe(true);
  expect(access("/khen-thuong-dot-xuat/31", { Success: true, DuocNhap: false })).toBe(true);
  const items = visibleGroups(user, null, null, null, null, { Success: true, DuocNhap: false }).flatMap((g) => g.items);
  expect(items.find((i) => i.path === "/khen-thuong-dot-xuat").name).toBe("Khen thưởng đột xuất của tôi");
  expect(items.some((i) => i.path === "/khen-thuong-dot-xuat/uy-quyen")).toBe(false);
});
